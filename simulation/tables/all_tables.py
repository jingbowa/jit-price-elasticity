"""Build every simulation table of the paper from the result files in simulation_results/.

    python tables/all_tables.py                 # all tables, a few seconds

Output, named by the paper's numbering (main text: Tables 1-5; Online Appendix: A2-A4):
    tables/Table_<n>.tex   LaTeX tabular in the paper's layout: row order, labels, columns and rounding as printed

    Table 1   Panel A  table_1_models.json          (simulation_codes/table_1_models.py)
              Panel B  table_5_supply.json          (simulation_codes/table_5_supply.py)
              Panel C  table_4_extra_models.json    (simulation_codes/table_4_extra_models.py)
    Table 2            table_6_literature.json      (simulation_codes/table_6_literature.py)
    Table 3            table_6_baseline_pricing.json (simulation_codes/table_6_baseline_pricing.py)
    Table 4   Panel A  table_2_scalability.json     (simulation_codes/table_2_scalability.py)
              Panel B  table_2_scalability_20.json  (simulation_codes/table_2_scalability_20.py)
    Table 5            table_3_tuning_full.json + table_3_tuning_full_extended.json, own elasticity
                       (also written as tables/table_3_opt_tuning_own.csv, the input of Figure A2)
    Table A2           table_A2_robustness.json     (simulation_codes/table_A2_robustness.py)
    Table A3  Panel A  table_3_tuning_full.json + table_3_tuning_full_extended.json, cross elasticity
              Panel B  table_3_tuning_reduced_form.json
    Table A4           table_A4_extra_primitives.json (simulation_codes/table_A4_extra_primitives.py)

Table A1 lists calibration inputs (simulation_results/calibrated_params.json, from
calibrate_literature.py). Table 6, Table A5 and Figure 2 are produced in ../empirical/.
"""
import sys
import os
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
