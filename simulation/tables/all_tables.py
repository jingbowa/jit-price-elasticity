def table_A2():
    fname = "table_A2_robustness.json"
    if not os.path.exists(f"{RES}/{fname}"):
        print(f"Table_A2: {fname} not found; run simulation_codes/table_A2_robustness.py")
        return
    res = load(fname)["results"]
    titles = {"A": "Panel A: Varying sample size ($J=4$ products)", "B": "Panel B: Varying number of products ($T=320{,}000$)",
              "C": "Panel C: Varying number of products ($T=5{,}120{,}000$)"}
    panels = []
    for panel in "ABC":
        rows = []
        for v in res.values():
            if v["panel"] != panel:
                continue
            spec = f"T={v['T']:,}" if panel == "A" else f"J={v['J']}"
            rows.append((f"${spec.replace('=', ' = ').replace(',', '{,}')}$", v["iterations"]))
        if rows:
            panels.append((panel, titles[panel], rows))
    elasticity_table("Table_A2", panels, "Specification", "Robustness checks.")


