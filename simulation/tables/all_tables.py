import csv
import json
import statistics

RES = "./simulation_results"
OUT = "./tables"
WRITTEN = []

MODELS_A = [("Logit", "Logit"), ("BLP_ind", "Independent RC Logit"), ("BLP_corr", "Correlated RC Logit")]
MODELS_B = [("sim_logit", "Logit"), ("sim_ind", "Independent RC Logit"), ("sim_corr", "Correlated RC Logit")]
MODELS_C = [("Complements", "Complementarity"), ("Variety", "Variety and Quantity")]
OBS = [10_000, 20_000, 40_000, 60_000]
PRODUCTS = list(range(4, 21, 2))


def load(name):
    with open(f"{RES}/{name}") as f:
        return json.load(f)


def f3(x):
    s = f"{x:.3f}"
    return "0.000" if s == "-0.000" else s


def fnum(x, d):
    s = f"{x:.{d}f}"
    return s.lstrip("-") if float(s) == 0 else s


def summary(iterations):
    """True value, mean estimate, bias, mean bootstrap SE and SD of estimates, for own and cross."""
    out = {}
    for kind in ("own", "cross"):
        true = statistics.mean(r[f"true_{kind}"] for r in iterations)
        est = [r[f"est_{kind}"] for r in iterations]
        mean = statistics.mean(est)
        out[kind] = [true, mean, mean - true, statistics.mean(r[f"se_{kind}"] for r in iterations),
                     statistics.stdev(est)]
    return out


def columns_of(d):
    """Table 1 Panel B stores lists per column; Panels A and C store one dict per iteration."""
    if isinstance(d, list):
        return d
    n = len(d["est_own"])
    return [{k: d[k][i] for k in d} for i in range(n)]


def write(table, header, body, note):
    with open(f"{OUT}/{table}.tex", "w") as f:
        f.write(f"% {table}: generated by tables/all_tables.py from simulation_results/. {note}\n")
        f.write(header + "\n" + "\n".join(body) + "\n\\bottomrule\n\\end{tabular}\n")
    WRITTEN.append(table)


def elasticity_table(table, panels, label_col, note):
    """Tables 1, A2, A4: rows of (label, own/cross, true, mean, bias, mean SE, SD)."""
    body = []
    for panel, title, rows in panels:
        if title:
            body.append(f"\\multicolumn{{7}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\")
        for i, (label, iterations) in enumerate(rows):
            s = summary(iterations)
            for kind in ("own", "cross"):
                lead = f"\\multirow{{2}}{{*}}{{{label}}}" if kind == "own" else ""
                body.append(f"{lead} & {kind} & " + " & ".join(f3(v) for v in s[kind]) + " \\\\")
            body.append("\\addlinespace" if i < len(rows) - 1 else "\\midrule")
        if body[-1] == "\\midrule" and panel == panels[-1][0]:
            body.pop()
    header = ("\\begin{tabular}{lcrrrrr}\n\\toprule\n" + label_col +
              " & Elasticity & True Value & Mean Estimate & Bias & Mean SE & Std. Dev. \\\\\n\\midrule")
    write(table, header, body, note)


def table_1():
    a, b, c = load("table_1_models.json"), load("table_5_supply.json"), load("table_4_extra_models.json")
    panels = [("A", "Panel A: Baseline Random-coefficient Logit Models", [(lab, a[k]) for k, lab in MODELS_A]),
              ("B", "Panel B: Supply-side Equilibrium", [(lab, columns_of(b[k])) for k, lab in MODELS_B]),
              ("C", "Panel C: Other Demand Models", [(lab, c[k]) for k, lab in MODELS_C])]
    elasticity_table("Table_1", panels, "Model", "Point-wise elasticity estimation.")


def table_2():
    d = load("table_6_literature.json")
    order = [("Logit_Wollmann", "Wollmann (2018) Logit", 2),
             ("RC_BLP", "BLP (1995) / CG (2020), RC Logit", 2),
             ("RC_Nevo", "Nevo (2001) / CG (2020), RC Logit", 3)]
    body = []
    for key, label, pd_ in order:
        r = d[key]
        for j in range(len(r["true_elas"])):
            te, be = r["true_elas"][j], r["bnn_elas_mean"][j]
            tp, bp, pb = r["true_p_star"][j], r["bnn_p_star_mean"][j], r["price_bias"][j]
            cells = [fnum(te, 2), fnum(be, 2), fnum(be - te, 2), fnum(tp, pd_), fnum(bp, pd_), fnum(pb, pd_)]
            lead = f"\\multirow{{4}}{{*}}{{{label}}}" if j == 0 else ""
            body.append(f"{lead} & {j + 1} & " + " & ".join(cells) + " \\\\")
        body.append("\\midrule")
    body.pop()
    header = ("\\begin{tabular}{lcrrrrrr}\n\\toprule\n & & \\multicolumn{3}{c}{Elasticity} & "
              "\\multicolumn{3}{c}{Pricing} \\\\\n\\cmidrule(lr){3-5} \\cmidrule(lr){6-8}\n"
              "DGP & Prod. & True $\\varepsilon$ & BNN $\\varepsilon$ & Bias & True $p^*$ & BNN $p^*$ & Bias \\\\\n\\midrule")
    write("Table_2", header, body, "Literature-calibrated DGPs; means over 10 Monte Carlo replications.")


def table_3():
    d = load("table_6_baseline_pricing.json")
    mean = statistics.mean
    body = []
    for key, label in (("logit", "Logit"), ("ind_rc", "Independent RC Logit"), ("corr_rc", "Correlated RC Logit")):
        r = d[key]
        tp, bp, bb = mean(r["true_p_star"]), mean(r["bnn_p_star_mean"]), mean(r["bnn_bias"])
        pp, pbias = mean(r["pyblp_p_star_mean"]), mean(r["pyblp_bias"])
        cells = [f3(tp), f3(bp), f3(bb), f"{r['bnn_time_mean']:.2f}s", f3(pp), f3(pbias),
                 f"{round(r['pyblp_time_mean']):,}s"]
        body.append(f"{label} & " + " & ".join(cells).replace(",", "{,}") + " \\\\")
    header = ("\\begin{tabular}{lrrrlrrl}\n\\toprule\n & & \\multicolumn{3}{c}{BNN} & \\multicolumn{3}{c}{PyBLP} \\\\\n"
              "\\cmidrule(lr){3-5} \\cmidrule(lr){6-8}\nModel & True $p^*$ & $p^*$ & bias & time & $p^*$ & bias & time \\\\\n\\midrule")
    write("Table_3", header, body, "Averages over the 4 products; timings are hardware-specific.")


