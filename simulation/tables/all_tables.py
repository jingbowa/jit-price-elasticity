def tuning_grid(results, models, field):
    grid = {}
    for key, v in results.items():
        m, n, j = key.split("|")
        grid.setdefault(m, {}).setdefault(int(n), {})[int(j)] = v[field]
    return {lab: grid[m] for m, lab in models}


def tuning_table(table, panels):
    body = []
    for title, grid in panels:
        if title:
            body.append(f"\\multicolumn{{11}}{{@{{}}l}}{{\\textit{{{title}}}}} \\\\")
        for label, by_n in grid.items():
            for i, n in enumerate(OBS):
                cells = [str(by_n[n][j]) for j in PRODUCTS]
                lead = f"\\multirow{{4}}{{*}}{{{label}}}" if i == 0 else ""
                body.append(f"{lead} & {n:,} & ".replace(",", "{,}", 1 if not lead else 0) + " & ".join(cells) + " \\\\")
            body.append("\\midrule")
    body.pop()
    header = ("\\begin{tabular}{llrrrrrrrrr}\n\\toprule\n & & \\multicolumn{9}{c}{Number of Products} \\\\\n"
              "\\cmidrule(l){3-11}\nModel & Obs. & " + " & ".join(map(str, PRODUCTS)) + " \\\\\n\\midrule")
    write(table, header, body, "MSE-minimising subsampling size m.")


def table_5():
    res = {**load("table_3_tuning_full.json"), **load("table_3_tuning_full_extended.json")}
    tuning_table("Table_5", [("", tuning_grid(res, MODELS_A, "optimal_own"))])
    # The same optima in the layout read by figures/all_figures.py (Figure A2).
    grid = {}
    for key, v in res.items():
        m, n, j = key.split("|")
        grid.setdefault((m, int(n)), {})[int(j)] = v["optimal_own"]
    with open(f"{OUT}/table_3_opt_tuning_own.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["model", "observations"] + PRODUCTS)
        for (m, n) in sorted(grid):
            w.writerow([m, n] + [grid[(m, n)][j] for j in PRODUCTS])


